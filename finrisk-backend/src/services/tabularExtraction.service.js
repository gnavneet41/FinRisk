const normalise = (label) =>
  String(label ?? "").toLowerCase().replace(/&/g, " ").replace(/[^a-z0-9]+/g, " ").trim();

const LABEL_TO_FIELD = new Map();
for (const [field, labels] of Object.entries(SYNONYMS)) {
  for (const l of labels) LABEL_TO_FIELD.set(normalise(l), field);
}

/** "1,234" -> 1234, "(121,983)" -> -121983, "$6.08" -> 6.08, otherwise null. */
export function parseNumber(raw) {
  if (typeof raw === "number") return Number.isFinite(raw) ? raw : null;
  if (raw === null || raw === undefined) return null;
  let s = String(raw).trim();
  if (!s) return null;
  let negative = false;
  if (/^\(.*\)$/.test(s)) { negative = true; s = s.slice(1, -1); }
  s = s.replace(/[$€£₹,\s]/g, "").replace(/^−/, "-");
  if (!/^-?\d+(\.\d+)?$/.test(s)) return null;
  const n = Number(s);
  return negative ? -n : n;
}

/** Turns table rows into the FinRisk field object. */
export function extractFromRows(rows) {
  const result = Object.fromEntries(FINANCIAL_FIELDS.map((f) => [f, null]));

  for (const row of rows) {
    const cells = row.map((c) => (c === null || c === undefined ? "" : c));
    const labelIndex = cells.findIndex((c) => typeof c === "string" && c.trim() && parseNumber(c) === null);
    if (labelIndex === -1) continue;

    const field = LABEL_TO_FIELD.get(normalise(cells[labelIndex]));
    if (!field || result[field] !== null) continue; // first match wins

    const rest = cells.slice(labelIndex + 1);
    if (field === "company" || field === "fiscal_year") {
      const text = rest.find((c) => String(c).trim());
      if (text !== undefined) {
        const value = String(text).trim();
        result[field] = field === "fiscal_year" && /^\d{4}$/.test(value) ? `FY${value}` : value;
      }
      continue;
    }

    for (const c of rest) {
      const n = parseNumber(c);
      if (n !== null) { result[field] = n; break; }
    }
  }
  return result;
}

/** Minimal CSV parser (handles quotes and commas inside quotes). */
export function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = "";
  let quoted = false;
  const src = String(text).replace(/^﻿/, "");

  for (let i = 0; i < src.length; i++) {
    const ch = src[i];
    if (quoted) {
      if (ch === '"' && src[i + 1] === '"') { field += '"'; i++; }
      else if (ch === '"') quoted = false;
      else field += ch;
    } else if (ch === '"') quoted = true;
    else if (ch === ",") { row.push(field); field = ""; }
    else if (ch === "\n" || ch === "\r") {
      if (ch === "\r" && src[i + 1] === "\n") i++;
      row.push(field); rows.push(row); row = []; field = "";
    } else field += ch;
  }
  if (field || row.length) { row.push(field); rows.push(row); }
  return rows.filter((r) => r.some((c) => c.trim()));
}

export function extractFromCsv(text) {
  const values = extractFromRows(parseCsv(text));
  console.log(`[Document Agent] CSV: ${countFound(values)} values found`);
  return values;
}

export async function extractFromXlsx(filePath) {
  const workbook = new ExcelJS.Workbook();
  await workbook.xlsx.readFile(filePath);

  const rows = [];
  workbook.eachSheet((sheet) => {
    sheet.eachRow({ includeEmpty: false }, (row) => {
      const values = [];
      row.eachCell({ includeEmpty: true }, (cell) => {
        let v = cell.value;
        if (v && typeof v === "object") {
          v = v.result ?? v.text ?? (v.richText ? v.richText.map((t) => t.text).join("") : null);
        }
        values.push(v);
      });
      rows.push(values);
    });
  });

  const values = extractFromRows(rows);
  console.log(`[Document Agent] Excel: ${countFound(values)} values found`);
  return values;
}

const countFound = (v) => Object.values(v).filter((x) => x !== null).length;


