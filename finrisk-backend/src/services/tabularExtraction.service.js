// TABULAR EXTRACTION (CSV and Excel)
// ------------------------------------------------------------
// Part of the Document Agent. Reads a two-column style table:
//
//   Line item,                 FY2024,  FY2023
//   Company Name,              Apple Inc.
//   Fiscal Year,               FY2024
//   Revenue (Total Net Sales), 391035,  383285
//   ...
//
// For each row, the label is matched to a FinRisk field using the
// synonym list below, and the FIRST number after the label is used
// (the current year). Unknown rows are ignored; missing fields stay
// null — nothing is estimated.
// ============================================================

import ExcelJS from "exceljs";

