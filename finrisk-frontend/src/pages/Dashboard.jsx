import { Link } from "react-router-dom";
import {
  DollarSign, TrendingUp, Wallet, Landmark, Droplets, Scale, Percent, Gauge, Upload as UploadIcon, ArrowRight
} from "lucide-react";
import { useAnalysis } from "../lib/analysis.jsx";
import { useAuth, canEdit } from "../lib/auth.jsx";
import { Alert, Button, Card, CardHeader, EmptyState, PageHeader, RiskBadge, Spinner, StatCard, cx } from "../components/ui.jsx";
import { MoneyBars, RatioBars } from "../components/charts.jsx";
import { CATEGORIES, RISK_STYLE, date, methodLabel, money, ratioValue } from "../lib/format.js";

export default function Dashboard() {
  const { document: doc, loading, completed, error } = useAnalysis();
  const { user } = useAuth();

  if (loading) return <Spinner />;
  if (error) return <Alert type="error">{error}</Alert>;
  if (!completed.length || !doc) return <NoAnalysis canUpload={canEdit(user)} />;

  const d = doc.financial_data;
  const r = doc.analysis.calculated_ratios;
  const risk = doc.risk_assessment;
  const overall = risk.overall_assessment.level;
  const categoryLevel = Object.fromEntries(risk.category_assessments.map((c) => [c.category, c]));

  return (
    <>
      <PageHeader
        title={`${doc.company_name ?? "Company"} ${doc.fiscal_year ?? ""}`}
        description={`Financial overview from ${doc.filename}, analysed ${date(doc.analyzed_at)}. Figures in USD millions.`}
        actions={
          <>
            <Link to="/analysis"><Button variant="secondary">Financial analysis</Button></Link>
            <Link to="/risk"><Button icon={ArrowRight}>Risk assessment</Button></Link>
          </>
        }
      />

      {/* Overall risk banner */}
      <Card className="mb-6 overflow-hidden">
        <div className="flex flex-col gap-5 p-5 sm:flex-row sm:items-center">
          <div className="flex items-center gap-4">
            <div className={cx("grid size-12 place-items-center rounded-xl", RISK_STYLE[overall].badge.split(" ").slice(0, 1))}>
              <Gauge className={cx("size-6", RISK_STYLE[overall].text)} />
            </div>
            <div>
              <p className="text-sm text-slate-500">Overall risk</p>
              <p className={cx("text-xl font-semibold", RISK_STYLE[overall].text)}>{RISK_STYLE[overall].label}</p>
            </div>
          </div>
          <p className="flex-1 text-sm leading-relaxed text-slate-600 sm:border-l sm:border-slate-200 sm:pl-5">
            {risk.overall_assessment.summary}
          </p>
        </div>
        <div className="flex flex-wrap gap-x-6 gap-y-1 border-t border-slate-100 bg-slate-50/60 px-5 py-2.5 text-xs text-slate-500">
          <span>Risk assessment: {methodLabel(risk.generated_by)}</span>
          <span>Ratios: Calculation Engine</span>
          <span>{risk.retrieved_knowledge?.length ?? 0} knowledge sources</span>
        </div>
      </Card>

      {/* KPIs */}
      <div className="grid grid-cols-2 gap-3 sm:gap-4 xl:grid-cols-4">
        <StatCard label="Revenue" value={money(d.revenue)} icon={DollarSign} hint="Total net sales" />
        <StatCard label="Net Income" value={money(d.net_income)} icon={TrendingUp} hint="After all expenses and tax" />
        <StatCard label="Operating Cash Flow" value={money(d.operating_cash_flow)} icon={Wallet} hint="Cash generated by operations" />
        <StatCard label="Total Debt" value={money(d.total_debt)} icon={Landmark} hint="Short-term + long-term debt" />
        <StatCard label="Current Ratio" value={ratioValue(r.current_ratio?.value)} icon={Droplets}
          hint={r.current_ratio?.value < 1 ? "Current liabilities exceed current assets" : "Current assets cover current liabilities"} />
        <StatCard label="Debt-to-Equity" value={ratioValue(r.debt_to_equity?.value)} icon={Scale}
          hint={r.debt_to_equity?.value > 1 ? "Debt exceeds shareholders' equity" : "Debt within equity"} />
        <StatCard label="Net Profit Margin" value={ratioValue(r.net_profit_margin?.value, "percent")} icon={Percent} hint="Net income / revenue" />
        <StatCard label="Return on Equity" value={ratioValue(r.return_on_equity?.value, "percent")} icon={TrendingUp} hint="Net income / equity" />
      </div>

      {/* Statements */}
      <div className="mt-6 grid gap-6 xl:grid-cols-2">
        <Card>
          <CardHeader title="From revenue to net income" subtitle="Income statement, USD millions" />
          <div className="px-3 pb-3 pt-4">
            <MoneyBars rows={[
              { label: "Revenue", value: d.revenue },
              { label: "Gross profit", value: d.gross_profit, muted: true },
              { label: "Op. income", value: d.operating_income, muted: true },
              { label: "Net income", value: d.net_income }
            ].filter((x) => typeof x.value === "number")} />
          </div>
        </Card>
        <Card>
          <CardHeader title="Where cash came from and went" subtitle="Cash flow statement, USD millions" />
          <div className="px-3 pb-3 pt-4">
            <MoneyBars rows={[
              { label: "Operating", value: d.operating_cash_flow },
              { label: "Investing", value: d.investing_cash_flow, muted: true },
              { label: "Financing", value: d.financing_cash_flow, muted: true },
              { label: "Net change", value: d.net_cash_change }
            ].filter((x) => typeof x.value === "number")} />
          </div>
        </Card>
      </div>

      {/* Category sections */}
      <h2 className="mb-4 mt-8 text-lg font-semibold text-slate-900">Analysis by category</h2>
      <div className="grid gap-6 lg:grid-cols-2">
        {CATEGORIES.map((cat) => {
          const rows = Object.values(r).filter((x) => x.category === cat.analysis)
            .map((x) => ({ label: x.name, value: x.value, unit: x.unit }));
          const assessment = categoryLevel[cat.risk];
          if (!rows.length) return null;
          return (
            <Card key={cat.key} className={cat.key === "cash_flow" ? "lg:col-span-2" : ""}>
              <CardHeader
                title={cat.name}
                subtitle={cat.question}
                action={assessment ? <RiskBadge level={assessment.level} /> : <span className="text-xs text-slate-500">Not rated</span>}
              />
              <div className="px-3 pt-3">
                <RatioBars rows={rows} reference={cat.key === "liquidity" || cat.key === "solvency" ? { value: 1, label: "1.0" } : null} />
              </div>
              <p className="border-t border-slate-100 px-5 py-3.5 text-sm leading-relaxed text-slate-600">
                {assessment?.summary ?? "Not rated: rating efficiency requires industry benchmarks, which are not available."}
              </p>
            </Card>
          );
        })}
      </div>
    </>
  );
}

export function NoAnalysis({ canUpload }) {
  return (
    <Card>
      <EmptyState
        icon={UploadIcon}
        title="No completed analysis yet"
        description={canUpload
          ? "Upload a financial statement (PDF, Excel or CSV). FinRisk extracts the values, calculates the ratios and assesses the risk."
          : "When an analyst in your company uploads and analyses a document, it will appear here."}
        action={canUpload && <Link to="/upload"><Button icon={UploadIcon}>Upload document</Button></Link>}
      />
    </Card>
  );
}
